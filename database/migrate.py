"""
Schema migrations: safe, ordered, repeatable.

- Migration files live in database/migrations/NNNN_name.sql and are applied
  in numeric order, each exactly once, inside one transaction (PostgreSQL
  has transactional DDL, so a failing migration leaves nothing behind).
- Applied versions are recorded in `schema_migrations`; re-running is a no-op.
- Nothing here ever DROPs or TRUNCATEs. Migrations must only add things.
- On PostgreSQL an advisory lock prevents two instances migrating at once.
- The app does NOT run this on startup. Run it explicitly:
      flask --app app db-migrate        (Railway: pre-deploy command)

Portable tokens substituted per engine:
    {{PK}}    auto-increment primary key
    {{NOW}}   default "current UTC timestamp as text"
    {{REAL}}  floating point type
"""

import hashlib
import os
import re
import sqlite3

MIGRATIONS_DIR = os.path.join(os.path.dirname(__file__), "migrations")
ADVISORY_LOCK_KEY = 727_4_2026

_TOKENS = {
    "sqlite": {
        "{{PK}}": "INTEGER PRIMARY KEY AUTOINCREMENT",
        "{{NOW}}": "(datetime('now'))",
        "{{REAL}}": "REAL",
    },
    "postgres": {
        "{{PK}}": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "{{NOW}}": "(to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'))",
        "{{REAL}}": "DOUBLE PRECISION",
    },
}

_FILE_RE = re.compile(r"^(\d{4})_[a-z0-9_]+\.sql$")


def render(sql: str, dialect: str) -> str:
    for token, value in _TOKENS[dialect].items():
        sql = sql.replace(token, value)
    return sql


def discover():
    """[(version:int, name:str, path:str)] sorted by version."""
    found = []
    for fname in os.listdir(MIGRATIONS_DIR):
        m = _FILE_RE.match(fname)
        if m:
            found.append((int(m.group(1)), fname, os.path.join(MIGRATIONS_DIR, fname)))
    found.sort()
    versions = [v for v, _, _ in found]
    if len(versions) != len(set(versions)):
        raise RuntimeError("Duplicate migration version numbers.")
    return found


def _checksum(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def _ensure_table(db):
    db.execute(
        """CREATE TABLE IF NOT EXISTS schema_migrations (
               version    INTEGER PRIMARY KEY,
               name       TEXT NOT NULL,
               checksum   TEXT NOT NULL,
               applied_at TEXT NOT NULL
           )"""
    )
    db.commit()


def applied(db) -> dict:
    _ensure_table(db)
    return {r["version"]: r for r in db.execute("SELECT * FROM schema_migrations").fetchall()}


def _split_sqlite(sql: str):
    """sqlite3 can't run multi-statement strings through execute(); split
    on statement boundaries using SQLite's own parser (handles comments/strings)."""
    statements, buf = [], ""
    for line in sql.splitlines(keepends=True):
        buf += line
        if sqlite3.complete_statement(buf):
            statements.append(buf)
            buf = ""
    if buf.strip() and not all(l.strip().startswith("--") or not l.strip() for l in buf.splitlines()):
        statements.append(buf)
    return statements


def apply_pending(db, log=print) -> list:
    """Apply all pending migrations. Returns the list of versions applied."""
    done = applied(db)
    newly = []

    if db.is_postgres:
        db.execute("SELECT pg_advisory_lock(?)", (ADVISORY_LOCK_KEY,))
        done = applied(db)  # re-read: another instance may have finished while we waited
    try:
        for version, fname, path in discover():
            with open(path, "r", encoding="utf-8") as f:
                raw = f.read()
            checksum = _checksum(raw)
            if version in done:
                if done[version]["checksum"] != checksum:
                    log(f"WARNING: migration {fname} was edited after being applied "
                        f"(checksum changed). Create a NEW migration instead of editing old ones.")
                continue

            rendered = render(raw, db.dialect)
            log(f"Applying migration {fname} ...")
            try:
                if db.is_postgres:
                    db.conn.cursor().execute(rendered)
                else:
                    for stmt in _split_sqlite(rendered):
                        db.conn.execute(stmt)
                db.execute(
                    "INSERT INTO schema_migrations (version, name, checksum, applied_at) "
                    "VALUES (?, ?, ?, datetime('now'))",
                    (version, fname, checksum), returning=False,
                )
                db.commit()
            except Exception:
                db.rollback()
                raise
            newly.append(version)
    finally:
        if db.is_postgres:
            db.execute("SELECT pg_advisory_unlock(?)", (ADVISORY_LOCK_KEY,))
            db.commit()

    if not newly:
        log("Database schema is up to date.")
    return newly
