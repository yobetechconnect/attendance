"""
Report generation: official-looking branded PDFs, plus CSV/Excel
exports for large record sets (Sections 27-29).

PDFs are built with reportlab (already available, no network
dependency) so the packaged app has zero extra install step for this
piece. Exports stream rather than building giant in-memory HTML so
they hold up for thousands of rows (Section 29/30).
"""

import csv
import io
import os

from openpyxl import Workbook
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Image, Paragraph, SimpleDocTemplate, Spacer,
                                 Table, TableStyle)

BRAND_BLUE = colors.HexColor("#0b3d5c")
BRAND_GOLD = colors.HexColor("#b8860b")


def _header_flowables(settings, report_title: str):
    styles = getSampleStyleSheet()
    school_style = ParagraphStyle("school", parent=styles["Title"], fontSize=16,
                                   textColor=BRAND_BLUE, spaceAfter=2)
    arabic_style = ParagraphStyle("arabic", parent=styles["Normal"], fontSize=13,
                                   alignment=1, spaceAfter=2)
    tagline_style = ParagraphStyle("tagline", parent=styles["Normal"], fontSize=9,
                                    textColor=BRAND_GOLD, spaceAfter=6)
    address_style = ParagraphStyle("address", parent=styles["Normal"], fontSize=8,
                                    textColor=colors.grey, spaceAfter=10)
    title_style = ParagraphStyle("report_title", parent=styles["Heading2"],
                                  textColor=colors.black, spaceBefore=4, spaceAfter=10)

    flow = []
    logo_path = settings["logo_path"]
    if logo_path and os.path.exists(logo_path):
        flow.append(Image(logo_path, width=22 * mm, height=22 * mm))
    flow.append(Paragraph(settings["school_name"], school_style))
    if settings["school_name_arabic"]:
        flow.append(Paragraph(settings["school_name_arabic"], arabic_style))
    flow.append(Paragraph(settings["tagline"], tagline_style))
    flow.append(Paragraph(settings["address"], address_style))
    flow.append(Paragraph(report_title, title_style))
    return flow


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(colors.grey)
    canvas.drawString(20 * mm, 12 * mm,
                       "Generated by the AL-ISTI'ANAH ACADEMY DAMATURU Attendance System — official record")
    canvas.drawRightString(190 * mm, 12 * mm, "Authorized signature: ____________________")
    canvas.restoreState()


def _base_table_style():
    return TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_BLUE),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f7fa")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ])


def build_student_report_pdf(settings, student, session_name, term_name, subject_rows) -> bytes:
    """subject_rows: list of dicts with subject, present, late, absent, excused, pct"""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=15 * mm, bottomMargin=20 * mm)
    styles = getSampleStyleSheet()

    flow = _header_flowables(settings, "Student Attendance Report")
    info = (
        f"<b>Name:</b> {student['first_name']} {student['surname']} &nbsp;&nbsp; "
        f"<b>Admission No:</b> {student['admission_number']}<br/>"
        f"<b>Class:</b> {student['class_name'] or '—'} &nbsp;&nbsp; "
        f"<b>Session:</b> {session_name or '—'} &nbsp;&nbsp; <b>Term:</b> {term_name or '—'}"
    )
    flow.append(Paragraph(info, styles["Normal"]))
    flow.append(Spacer(1, 8))

    data = [["Subject", "Present", "Late", "Absent", "Excused", "Attendance %"]]
    for r in subject_rows:
        data.append([r["subject"], r["present"], r["late"], r["absent"], r["excused"], f"{r['pct']:.1f}%"])
    table = Table(data, repeatRows=1, colWidths=[55 * mm, 22 * mm, 18 * mm, 20 * mm, 20 * mm, 28 * mm])
    table.setStyle(_base_table_style())
    flow.append(table)

    doc.build(flow, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def build_class_report_pdf(settings, class_row, session_name, term_name, student_rows) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=15 * mm, bottomMargin=20 * mm)
    styles = getSampleStyleSheet()

    flow = _header_flowables(settings, f"Class Attendance Report — {class_row['name']}")
    info = f"<b>Session:</b> {session_name or '—'} &nbsp;&nbsp; <b>Term:</b> {term_name or '—'}"
    flow.append(Paragraph(info, styles["Normal"]))
    flow.append(Spacer(1, 8))

    data = [["Admission No", "Student Name", "Present", "Late", "Absent", "Excused", "%"]]
    for r in student_rows:
        data.append([r["admission_number"], r["name"], r["present"], r["late"],
                     r["absent"], r["excused"], f"{r['pct']:.1f}%"])
    table = Table(data, repeatRows=1)
    table.setStyle(_base_table_style())
    flow.append(table)

    doc.build(flow, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def export_csv(rows: list, fieldnames: list) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fieldnames, extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        writer.writerow(row)
    return buf.getvalue()


def export_excel(rows: list, fieldnames: list, sheet_title: str = "Report") -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_title[:31]
    ws.append(fieldnames)
    for row in rows:
        ws.append([row.get(f, "") for f in fieldnames])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
